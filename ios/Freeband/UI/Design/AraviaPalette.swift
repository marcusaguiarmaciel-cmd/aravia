import SwiftUI
import UIKit

/// Aravia's colours, taken from the materials of Brazil's original peoples: urucum (annatto red),
/// jenipapo (the blue-black of body paint), palha (straw), barro (clay), mata (forest), ocre
/// (tabatinga clay) and rio (river). The app's tokens (design/tokens.json) use the same values;
/// these are for drawings that are not themed (map routes, the Story video).
enum AraviaPalette {
    static let urucum = UIColor(hex: 0xC0412A)
    static let urucumDeep = UIColor(hex: 0x8E2A1E)
    static let jenipapo = UIColor(hex: 0x16202B)
    static let palha = UIColor(hex: 0xE9D9B8)
    static let barro = UIColor(hex: 0x9C5536)
    static let mata = UIColor(hex: 0x2C7A50)
    static let ocre = UIColor(hex: 0xC98A1F)
    static let rio = UIColor(hex: 0x1D727E)
}
