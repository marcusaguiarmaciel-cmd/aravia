#!/usr/bin/env python3
"""Copies what the iOS app and the Android app must share into the Android project, so the two
never drift apart: the arara's shapes (ios/Freeband/UI/Train/Arara.swift), the legal texts
(ios/Freeband/Account/Legal.swift) and the colour tokens (design/tokens.json).

    python3 scripts/gen_android_shared.py

Writes android/app/src/main/assets/arara.json, .../legal/LegalText.kt and .../ui/Tokens.kt.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
IOS = ROOT / "ios/Freeband"
OUT = ROOT / "android/app/src/main"
PKG = OUT / "java/app/aravia"


def arara():
    src = (IOS / "UI/Train/Arara.swift").read_text()
    stages = {}
    for m in re.finditer(r"case \.(\w+): \[\n(.*?)\n        \]", src, re.S):
        layers = re.findall(r'L\(\.(\w+), 0x([0-9A-F]{6}), ([\d.]+), "([^"]+)"\)', m.group(2))
        if layers:
            stages[m.group(1)] = [{"role": r, "rgb": int(h, 16), "alpha": float(a), "d": d} for r, h, a, d in layers]
    assert set(stages) == {"egg", "chick", "young", "adult", "royal", "legend"}, stages.keys()
    (OUT / "assets").mkdir(parents=True, exist_ok=True)
    (OUT / "assets/arara.json").write_text(json.dumps(stages, ensure_ascii=False, separators=(",", ":")))
    return sum(len(v) for v in stages.values())


def swift_string(body, consts):
    """A Swift multi-line literal: backslash at a line end joins lines, \\(name) interpolates."""
    lines = body.split("\n")
    indent = min(len(l) - len(l.lstrip()) for l in lines if l.strip())
    text = ""
    for line in lines:
        line = line[indent:]
        if line.endswith("\\"):
            text += line[:-1]
        else:
            text += line + "\n"
    text = text.rstrip("\n")
    return re.sub(r"\\\((\w+)\)", lambda m: str(consts[m.group(1)]), text)


def legal():
    src = (IOS / "Account/Legal.swift").read_text()
    consts = dict(re.findall(r'static let (\w+) = "([^"]*)"', src))
    consts["version"] = int(re.search(r"static let version = (\d+)", src).group(1))
    # Runtime Kotlin expressions for build-injected controller document (never committed to git).
    consts["controllerLine"] = "__CONTROLLER_LINE__"
    consts["controllerInline"] = "__CONTROLLER_INLINE__"
    health = re.search(r'static let healthConsent = """\n(.*?)\n\s*"""', src, re.S).group(1)

    def sections(name):
        block = re.search(rf"static let {name}: \[Section\] = \[(.*?)\n    \]", src, re.S).group(1)
        return [(t, swift_string(b, consts)) for t, b in
                re.findall(r'Section\(title: "([^"]+)", body: """\n(.*?)\n\s*"""\)', block, re.S)]

    def kt(s):
        android_s = (
            s.replace("no seu iPhone", "no seu celular")
             .replace("Keychain do iPhone", "Keystore do Android")
             .replace("(Keychain)", "(Android Keystore)")
             .replace(
                 "O Aravia não vende dados, não mostra anúncios, não usa ferramentas de análise ou rastreamento",
                 "O Aravia não vende dados, não exibe anúncios invasivos nem rastreadores (anúncios premiados opcionais via Google AdMob, não personalizados, só aparecem quando você escolhe assistir 2 anúncios para liberar 24h de Premium, sem compartilhar nenhum dado de saúde)",
             )
        )
        encoded = json.dumps(android_s, ensure_ascii=False).replace("$", "\\$")
        encoded = encoded.replace("__CONTROLLER_LINE__", "$controllerLine")
        encoded = encoded.replace("__CONTROLLER_INLINE__", "$controllerInline")
        return encoded

    cname = json.dumps(consts["controllerName"], ensure_ascii=False)
    cname_raw = consts["controllerName"].replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    out = ["// Generated by scripts/gen_android_shared.py from ios/Freeband/Account/Legal.swift. Do not edit.",
           "package app.aravia.legal", "",
           "import app.aravia.BuildConfig", "",
           "object LegalText {",
           f"    const val VERSION = {consts['version']}",
           f"    const val EFFECTIVE_DATE = {kt(consts['effectiveDate'])}",
           f"    const val CONTACT_EMAIL = {kt(consts['contactEmail'])}",
           f"    const val HEALTH_CONSENT = {kt(swift_string(health, consts))}",
           "",
           "    private val controllerDoc: String",
           "        get() = BuildConfig.LEGAL_CONTROLLER_DOC.trim()",
           "    private val controllerLine: String",
           f'        get() = if (controllerDoc.isEmpty()) {cname} else "{cname_raw} · $controllerDoc"',
           "    private val controllerInline: String",
           f'        get() = if (controllerDoc.isEmpty()) {cname} else "{cname_raw} ($controllerDoc)"',
           "", "    data class Section(val title: String, val body: String)", ""]
    for name, kname in (("terms", "TERMS"), ("privacy", "PRIVACY")):
        out.append(f"    val {kname} = listOf(")
        for t, b in sections(name):
            out.append(f"        Section({kt(t)}, {kt(b)}),")
        out.append("    )")
    out.append("}")
    (PKG / "legal").mkdir(parents=True, exist_ok=True)
    (PKG / "legal/LegalText.kt").write_text("\n".join(out) + "\n")


def tokens():
    t = json.loads((ROOT / "design/tokens.json").read_text())
    out = ["// Generated by scripts/gen_android_shared.py from design/tokens.json. Do not edit.",
           "package app.aravia.ui", "", "import androidx.compose.ui.graphics.Color", "",
           "/** The app's colours, light and dark, the same values the iOS app uses. */",
           "object Tokens {"]
    for name, entry in t["color"].items():
        if not isinstance(entry, dict) or "light" not in entry:
            continue
        def c(h):
            return "Color(0xFF" + h.lstrip("#").upper() + ")"
        out.append(f"    val {name}Light = {c(entry['light'])}")
        out.append(f"    val {name}Dark = {c(entry['dark'])}")
    out.append("}")
    (PKG / "ui").mkdir(parents=True, exist_ok=True)
    (PKG / "ui/Tokens.kt").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    n = arara()
    legal()
    tokens()
    print(f"arara.json ({n} shapes), LegalText.kt, Tokens.kt")
